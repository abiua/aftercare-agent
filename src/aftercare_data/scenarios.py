"""Frozen simulated requests and their separately authored acceptance oracles."""

from copy import deepcopy
from datetime import datetime, timedelta

OBSERVED_AT = datetime.fromisoformat("2026-11-10T12:00:00+08:00")

POLICIES = {
    "cancel": (1, 2, 3, 4, 5, 7, 8, 9, 10, 12),
    "return": (1, 2, 5, 7, 8, 9, 10, 12),
    "damaged": (1, 2, 6, 8, 9, 10, 12),
    "partial_refund": (1, 2, 8, 9, 10, 12),
    "refund_status": (1, 8, 12),
    "warranty": (1, 5, 11),
}


def _timestamp(value):
    return value.isoformat() if value is not None else None


def _event(kind, *, after=1, **details):
    return {"type": kind, "at": _timestamp(OBSERVED_AT + timedelta(seconds=after)), **details}


def _payment_result(status="SUCCEEDED", *, after=4):
    return _event("REFUND_CALL_RESULT", after=after, status=status)


def _approval(status, *, after=2):
    return _event("APPROVAL_RESULT", after=after, status=status)


def _line(product, unit, *, quantity=1, discount=0, refunded=0):
    return (product, quantity, unit, discount, refunded)


def _photo(kind, *, line_id=None, index=1):
    return {"id": f"{kind.lower()}-{index}", "kind": kind, "line_id": line_id}


def _build_case(
    data,
    number,
    family,
    request,
    utterances,
    *,
    status="PAID",
    payment_status=None,
    foreign_actor=False,
    delivered_age=None,
    lines=None,
    requested_lines=None,
    requested_refund=None,
    requested_fee=0,
    fulfillment="UNVERIFIED",
    return_receipt="NOT_RECEIVED",
    inspection="NOT_STARTED",
    attachments=(),
    ledger=(),
    events=(),
    merchant_concession=False,
):
    order_base = data["orders"][number - 1]
    customer_id = order_base["customer_id"]
    actor_id = customer_id
    if foreign_actor:
        actor_id = next(row["id"] for row in data["customers"] if row["id"] != customer_id)

    has_payment = status != "UNPAID"
    payment_status = payment_status or ("CONFIRMED" if has_payment else "UNPAID")
    shipped = status in {"SHIPPED", "DELIVERED"}
    if status == "DELIVERED":
        age = delivered_age if delivered_age is not None else timedelta(hours=24 + number)
        delivered_at = OBSERVED_AT - age
        shipped_at = delivered_at - timedelta(days=2)
        created_at = shipped_at - timedelta(days=1)
    else:
        delivered_at = None
        created_at = OBSERVED_AT - timedelta(hours=12 + number)
        shipped_at = created_at + timedelta(hours=4) if shipped else None
    paid_at = created_at + timedelta(minutes=15) if has_payment else None
    cancelled_at = created_at + timedelta(hours=2) if status == "CANCELLED" else None

    returnable = sorted(
        (item for item in data["products"] if item["returnable"]), key=lambda item: item["id"]
    )
    if lines is None:
        lines = [
            _line(returnable[number % len(returnable)], 12000 + number * 31, discount=number * 3)
        ]
    items = []
    for index, (product, quantity, unit, discount, refunded) in enumerate(lines, 1):
        items.append(
            {
                "line_id": f"L{index:02d}",
                "product_id": product["id"],
                "quantity": quantity,
                "unit_price_cents": unit,
                "discount_cents": discount,
                "payable_cents": quantity * unit - discount,
                "paid_cents": quantity * unit - discount if has_payment else 0,
                "refunded_cents": refunded,
            }
        )
    order = {
        "id": order_base["id"],
        "customer_id": customer_id,
        "status": status,
        "payment_status": payment_status,
        "created_at": _timestamp(created_at),
        "paid_at": _timestamp(paid_at),
        "shipped_at": _timestamp(shipped_at),
        "delivered_at": _timestamp(delivered_at),
        "cancelled_at": _timestamp(cancelled_at),
        "items": items,
        "subtotal_cents": sum(item["quantity"] * item["unit_price_cents"] for item in items),
        "discount_cents": sum(item["discount_cents"] for item in items),
        "payable_cents": sum(item["payable_cents"] for item in items),
        "paid_cents": sum(item["paid_cents"] for item in items),
        "refunded_cents": sum(item["refunded_cents"] for item in items),
    }
    shipment = None
    if shipped:
        shipment = {
            "id": f"SC-S{number:03d}",
            "order_id": order["id"],
            "status": "DELIVERED" if delivered_at else "IN_TRANSIT",
            "carrier": "模拟快递",
            "tracking_number": f"SC-TRACK-{number:03d}",
            "shipped_at": order["shipped_at"],
            "delivered_at": order["delivered_at"],
        }
    line_ids = [item["line_id"] for item in items]
    selected_lines = list(requested_lines) if requested_lines is not None else line_ids
    resolution = None
    if merchant_concession:
        resolution = {
            "id": f"sc-resolution-{number:03d}",
            "type": "MERCHANT_CONCESSION",
            "status": "APPROVED",
            "line_ids": list(selected_lines),
            "approved_at": _timestamp(OBSERVED_AT - timedelta(minutes=number + 1)),
        }
    request_key = f"sc-refund-{number:03d}"
    entries = []
    for entry_status, line_amounts, current_key in ledger:
        entries.append(
            {
                "idempotency_key": request_key if current_key else f"sc-earlier-{number:03d}",
                "status": entry_status,
                "amount_cents": sum(line_amounts.values()),
                "line_amounts_cents": dict(line_amounts),
                "created_at": _timestamp(OBSERVED_AT - timedelta(minutes=number)),
            }
        )

    recorded_events = deepcopy(list(events))
    for event in recorded_events:
        if event["type"] in {"REFUND_CALL_RESULT", "REFUND_QUERY_RESULT", "REQUEST_REPLAY"}:
            event["idempotency_key"] = request_key

    return {
        "id": f"CASE{number:03d}",
        "split": "dev" if number <= 40 else "test",
        "family": family,
        "utterances": list(utterances),
        "actor_customer_id": actor_id,
        "order_id": order["id"],
        "policy_ids": [f"POL{index:02d}" for index in POLICIES[request]],
        "fixture": {
            "as_of": _timestamp(OBSERVED_AT),
            "order": order,
            "shipment": shipment,
            "products": [deepcopy(product) for product, *_ in lines],
            "request": {
                "kind": request.upper(),
                "line_ids": selected_lines,
                "refund_cents": requested_refund,
                "fee_cents": requested_fee,
                "idempotency_key": request_key,
            },
            "fulfillment_status": fulfillment,
            "attachments": deepcopy(list(attachments)),
            "return": {"receipt_status": return_receipt, "inspection_status": inspection},
            "refund_ledger": entries,
            "resolution": resolution,
        },
        "events": sorted(recorded_events, key=lambda event: event["at"]),
    }


